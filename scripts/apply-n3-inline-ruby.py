def concat_block(b):
    """Return the original text reconstructed from a block's tokens (text token .v + ruby token .k)."""
    if b["kind"] in ("paragraph", "callout"):
        out = []
        for tok in b["tokens"]:
            if tok["t"] == "text":
                out.append(tok["v"])
            elif tok["t"] == "ruby":
                out.append(tok["k"])
            else:
                raise SystemExit(f"unexpected token kind {tok['t']!r} in {b}")
        return "".join(out)
    if b["kind"] == "list":
        # list block text equivalence = newline-joined item texts (but originally a single text token with embedded newlines)
        parts = []
        for item in b["items"]:
            sub = []
            for tok in item["tokens"]:
                if tok["t"] == "text":
                    sub.append(tok["v"])
                elif tok["t"] == "ruby":
                    sub.append(tok["k"])
            parts.append("".join(sub))
        return parts
    raise SystemExit(f"unexpected block kind {b['kind']!r}")


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    n3_dir = os.path.join(root, "server", "data", "corpus", "grammar", "N3")

    failed = []
    written = []

    for slug, new_blocks in NEW_BLOCKS.items():
        path = os.path.join(n3_dir, f"{slug}.json")
        if not os.path.exists(path):
            failed.append(f"{slug}: file missing at {path}")
            continue
        with open(path, encoding="utf-8") as f:
            d = json.load(f)

        old_blocks = d.get("explanation_ja_blocks") or []

        # Per-block concat invariant: each NEW block must have the same text concat
        # as the matching OLD block at the same index. Number of blocks must match.
        if len(old_blocks) != len(new_blocks):
            failed.append(f"{slug}: block count mismatch (old={len(old_blocks)}, new={len(new_blocks)})")
            continue

        per_block_ok = True
        for i, (old, new) in enumerate(zip(old_blocks, new_blocks)):
            if old["kind"] != new["kind"]:
                failed.append(f"{slug} block {i}: kind mismatch (old={old['kind']}, new={new['kind']})")
                per_block_ok = False
                continue
            if old["kind"] in ("paragraph", "callout"):
                old_text = "".join(tok.get("v", "") for tok in old.get("tokens", []) if tok["t"] == "text")
                new_text = concat_block(new)
                if old_text != new_text:
                    failed.append(f"{slug} block {i}: text mismatch\n  OLD: {old_text!r}\n  NEW: {new_text!r}")
                    per_block_ok = False
            elif old["kind"] == "list":
                old_items = ["".join(tok.get("v", "") for tok in item.get("tokens", []) if tok["t"] == "text") for item in old.get("items", [])]
                new_items = concat_block(new)
                if old_items != new_items:
                    failed.append(f"{slug} block {i}: list items mismatch\n  OLD: {old_items!r}\n  NEW: {new_items!r}")
                    per_block_ok = False

        if not per_block_ok:
            continue

        # Replace explanation_ja_blocks and write back preserving 2-space indent + final newline + no ASCII escape.
        d["explanation_ja_blocks"] = new_blocks
        with open(path, "w", encoding="utf-8") as f:
            json.dump(d, f, ensure_ascii=False, indent=2)
            f.write("\n")
        written.append(slug)

    if failed:
        print("FAILURES:")
        for fail in failed:
            print("  -", fail)
        sys.exit(1)

    print(f"Wrote {len(written)} files:")
    for slug in written:
        print(f"  {slug}.json")


if __name__ == "__main__":
    main()
