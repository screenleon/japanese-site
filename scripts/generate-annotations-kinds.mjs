#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(scriptDir, "..");
const apiTypesPath = resolve(repoRoot, "web/src/apiTypes.ts");
const outPath = resolve(scriptDir, "annotations-kinds.txt");

const source = readFileSync(apiTypesPath, "utf8");
const match = source.match(/export\s+const\s+ANNOTATION_KINDS\s*=\s*\[([\s\S]*?)\]\s+as\s+const/);
if (!match) {
  throw new Error("Could not find ANNOTATION_KINDS in web/src/apiTypes.ts");
}

const kinds = [...match[1].matchAll(/"([^"]+)"/g)].map((item) => item[1]);
if (kinds.length === 0) {
  throw new Error("ANNOTATION_KINDS is empty");
}

const header =
  "# Generated by scripts/generate-annotations-kinds.mjs from web/src/apiTypes.ts ANNOTATION_KINDS — do not edit by hand.";
writeFileSync(outPath, `${header}\n${kinds.join("\n")}\n`, "utf8");
